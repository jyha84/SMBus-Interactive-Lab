const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {JSDOM}=require(process.env.JSDOM_PATH||'jsdom');
const root=path.resolve(__dirname,'../dist');
async function main(){
  const dom=new JSDOM('<div id="host"></div>',{url:'https://example.test/',runScripts:'outside-only'}),w=dom.window;
  w.eval(fs.readFileSync(root+'/engine.js','utf8')+'\n'+fs.readFileSync(root+'/verification.js','utf8'));
  const checks=vm.runInNewContext(fs.readFileSync(root+'/app.js','utf8').match(/const checks=(\[.*?\]);/s)[1]);
  const host=w.document.querySelector('#host'),$=s=>host.querySelector(s),all=s=>[...host.querySelectorAll(s)];
  let saved={checks:[0],notes:{pec:'keep this note'},done:['pec']},savedText='',output;
  const esc=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const mount=()=>w.SMBVerification.mount({host,checks,saved,esc,save:()=>savedText=JSON.stringify(saved),download:(name,text,type)=>output={name,text,type}});
  const change=(s,value)=>{$(s).value=value;$(s).dispatchEvent(new w.Event('change'));};
  const input=(s,value)=>{$(s).value=value;$(s).dispatchEvent(new w.Event('input'));};
  mount();
  assert.equal(all('[data-case]').length,25);
  assert.equal($('[data-check="0"]').checked,true);
  assert.equal($('[data-result="0"]').value,'untested','legacy check must not imply PASS');
  assert.equal($('[data-summary="pass"] strong').textContent,'0');
  input('[data-context="dut"]','Board A');
  input('[data-record="16"][data-field="measured"]','PEC mismatch detected; data unchanged');
  input('[data-record="16"][data-field="evidence"]','D:\\capture\\crc,01.csv');
  input('[data-record="16"][data-field="reason"]','=HYPERLINK("example")');
  change('[data-result="16"]','fail');
  change('[data-result="1"]','na');
  assert.equal($('[data-summary="fail"] strong').textContent,'1');
  assert.equal($('[data-summary="na"] strong').textContent,'1');
  change('#verify-status','fail');assert.equal(all('[data-case]').filter(e=>!e.hidden).length,1);
  change('#verify-category','AC');assert.equal($('#verify-empty').hidden,false);
  change('#verify-status','');change('#verify-category','');
  input('#verify-search','PEC mismatch detected');assert.equal(all('[data-case]').filter(e=>!e.hidden).length,1);
  input('#verify-search','');
  $('#check-export').click();const exported=JSON.parse(output.text);
  assert.equal(exported.schema,'smbus-verification-v1');assert.equal(exported.verification.context.dut,'Board A');
  assert.equal(exported.verification.records['SMB-17'].status,'fail');assert.equal(exported.checklist[0].checked,true);
  $('#verify-csv').click();assert.ok(output.text.startsWith('\ufeff'));assert.ok(output.text.includes("' =")==false);
  assert.ok(output.text.includes('"\'=HYPERLINK(""example"")"'),'CSV formula must be neutralized');
  assert.ok(output.text.includes('"D:\\capture\\crc,01.csv"'));assert.equal(output.text.split('\r\n').length,26);
  saved=JSON.parse(savedText);mount();
  assert.equal($('[data-result="16"]').value,'fail');assert.equal($('[data-context="dut"]').value,'Board A');
  assert.equal($('[data-check="0"]').checked,true);
  async function upload(data){const element=$('#verify-file');Object.defineProperty(element,'files',{configurable:true,value:[{size:100,text:async()=>JSON.stringify(data)}]});await element.onchange({target:element});}
  const before=JSON.stringify(saved);
  await upload({spec:'3.3',schema:'smbus-verification-v1',verification:{context:{dut:'bad overwrite'},records:{'SMB-99':{status:'pass'}}}});
  assert.equal(JSON.stringify(saved),before,'invalid import must be atomic');assert.match($('#verify-message').textContent,/실패/);
  await upload({spec:'3.3',schema:'smbus-verification-v1',verification:{context:{dut:'Board B'},records:{'SMB-17':{status:'pass',measured:'<img src=x onerror=alert(1)>'}}}});
  assert.equal(saved.verification.context.dut,'Board B');assert.equal(saved.verification.records['SMB-17'].status,'pass');
  assert.equal(saved.verification.records['SMB-02'].status,'na','unmentioned records retained');
  assert.equal(saved.notes.pec,'keep this note');assert.deepEqual(saved.done,['pec']);assert.equal(host.querySelector('img'),null);
  assert.equal($('[data-record="16"][data-field="measured"]').value,'<img src=x onerror=alert(1)>');
  await upload({spec:'3.3',checklist:[{category:checks[0][0],item:checks[0][1],checked:false}]});
  assert.equal($('[data-check="0"]').checked,false);assert.equal(saved.verification.records['SMB-17'].status,'pass');
  assert.throws(()=>w.SMBVerification.parseImport({spec:'3.3',schema:'future',checklist:[]},checks));
  for(const s of ['=1+1',' +SUM(A1)','\t@SUM(A1)','-2'])assert.ok(w.SMBVerification.csvCell(s).startsWith('"\''));
  dom.window.close();console.log('Verification: legacy preservation, status/filter persistence, JSON merge/validation/XSS safety and CSV escaping passed.');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
